import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
await mkdir('test-results/screenshots', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: 'th-TH', timezoneId: 'Asia/Bangkok' });
await page.goto('http://127.0.0.1:5173');
await page.evaluate(() => document.fonts.ready);
await page.screenshot({ path: 'test-results/screenshots/landing.png', fullPage: true });
await page.getByRole('button', { name: 'ลองใช้งานเดโม', exact: true }).click();
await page.screenshot({ path: 'test-results/screenshots/dashboard.png', fullPage: true });
await page.locator('.side-nav').getByRole('button', { name: 'ปฏิทิน', exact: true }).click();
await page.screenshot({ path: 'test-results/screenshots/calendar.png', fullPage: true });
await page.locator('.side-nav').getByRole('button', { name: 'โปรเจ็คของฉัน', exact: true }).click();
await page.getByRole('button', { name: 'สร้างโปรเจ็ค', exact: true }).click();
await page.screenshot({ path: 'test-results/screenshots/create.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.emulateMedia({ reducedMotion: 'reduce' });
await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 0);
await page.screenshot({ path: 'test-results/screenshots/mobile-create.png', fullPage: true });
await browser.close();
console.log('Saved five screenshots in demo/test-results/screenshots');
